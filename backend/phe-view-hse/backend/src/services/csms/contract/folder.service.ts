/**
 * Generate assessment dates between start and end date at 6-month intervals
 * Starting from 6 months after start date
 * @param startDate 
 * @param endDate 
 * @returns Array of dates at 6-month intervals
 */
export function generateAssessmentDates(startDate: Date, endDate: Date): Date[] {
  const dates: Date[] = [];
  // Start from 6 months after the start date
  const current = new Date(startDate);
  current.setMonth(current.getMonth() + 6);
  
  // Generate dates every 6 months strictly before end date
  // The end date is reserved for Penilaian Akhir (PA)
  while (current < endDate) {
    dates.push(new Date(current));
    // Add 6 months
    current.setMonth(current.getMonth() + 6);
  }
  
  return dates;
}

/**
 * Create contract folders with assessment dates
 * @param contractId 
 * @param tx 
 */
export async function createContractFolders(
  contractId: string,
  tx: DbOrTx = db
) {
  // Get contract details
  const contractData = await getContractById(contractId);

  if (!contractData) {
    throw new Error(`Contract with ID ${contractId} not found`);
  }

  // Generate assessment dates (starting 6 months after start date)
  const startDate = new Date(contractData.startDate);
  const endDate = new Date(contractData.endDate);
  const assessmentDates = generateAssessmentDates(startDate, endDate);
  
  // Get the final assessment date from the contract
  const finalAssessmentDate = new Date(contractData.finalAssessmentDate);
  
  // Update contract with assessment dates (excluding the final assessment date)
  // Only PB dates should be in nearestOngoingAssessmentDate
  await tx.update(contract).set({
    nearestOngoingAssessmentDate: assessmentDates as any,
    finalAssessmentDate: finalAssessmentDate.toISOString().split('T')[0],
    updatedAt: sql`NOW()`,
  }).where(eq(contract.id, contractId));

  // Create folders for each assessment date (previously limited to 4, now create all)
  const mainFoldersToCreate = assessmentDates.length;
  const createdFolderIds: string[] = [];
  
  for (let i = 0; i < mainFoldersToCreate; i++) {
    const date = assessmentDates[i];
    // Format date as DD-MM-YYYY for folder name
    const formattedDate = `${String(date.getDate()).padStart(2, '0')}-${String(date.getMonth() + 1).padStart(2, '0')}-${date.getFullYear()}`;
    
    // All these are PB folders
    const folderType = "PB";
    const folderName = `${formattedDate} - ${folderType}`;
    const description = `Penilaian Berjalan for ${formattedDate}`;
    
    // Create main folder (ID will be auto-generated by database)
    const [newFolder] = await tx.insert(contractFolder).values({
      contractId,
      name: folderName,
      description: description,
      path: sql`''::ltree`, // Temporary empty path, will update after getting the ID
      fileType: "folder",
      isComplete: false, // Initialize as not complete
      assessmentDate: date,
      createdAt: new Date(),
      updatedAt: new Date(),
    }).returning();
    
    // Now update the path with the correct value using the generated ID
    await tx.update(contractFolder).set({
      path: sql`${newFolder.id}::ltree`,
      updatedAt: new Date(),
    }).where(eq(contractFolder.id, newFolder.id));
    
    createdFolderIds.push(newFolder.id);
  }

  // Also create the PA folder for the final assessment date if not already existing
  const existingPAFolder = await tx.query.contractFolder.findFirst({
    where: (fields, { eq, and, like }) => 
      and(
        eq(fields.contractId, contractId),
        like(fields.name, '% - PA')
      ),
  });
  
  if (!existingPAFolder) {
    const formattedFinalDate = `${String(finalAssessmentDate.getDate()).padStart(2, '0')}-${String(finalAssessmentDate.getMonth() + 1).padStart(2, '0')}-${finalAssessmentDate.getFullYear()}`;
    const paFolderName = `${formattedFinalDate} - PA`;
    const paDescription = `Penilaian Akhir for ${formattedFinalDate}`;
    
    // Create PA folder (ID will be auto-generated by database)
    const [paFolder] = await tx.insert(contractFolder).values({
      contractId,
      name: paFolderName,
      description: paDescription,
      path: sql`''::ltree`, // Temporary empty path, will update after getting the ID
      fileType: "folder",
      assessmentDate: finalAssessmentDate,
      createdAt: new Date(),
      updatedAt: new Date(),
    }).returning();

    // Now update the path with the correct value using the generated ID
    await tx.update(contractFolder).set({
      path: sql`${paFolder.id}::ltree`,
      updatedAt: new Date(),
    }).where(eq(contractFolder.id, paFolder.id));
    
    createdFolderIds.push(paFolder.id);
  }

  // Check if PSB folder already exists for this contract
  const existingPSBFolders = await tx.query.contractFolder.findMany({
    where: (fields, { eq, and, like }) => 
      and(
        eq(fields.contractId, contractId),
        like(fields.name, '% - PSB')
      ),
  });

  // Only create PSB folder if it doesn't already exist
  if (existingPSBFolders.length === 0) {
    // Create PSB folder (H+1 month after contract start date)
    const psbDate = new Date(startDate);
    psbDate.setMonth(psbDate.getMonth() + 1);
    
    // Check if PSB date is within contract period
    if (psbDate >= startDate && psbDate <= endDate) {
      // Format PSB date as DD-MM-YYYY for folder name
      const formattedPSBDate = `${String(psbDate.getDate()).padStart(2, '0')}-${String(psbDate.getMonth() + 1).padStart(2, '0')}-${psbDate.getFullYear()}`;
      const psbFolderName = `${formattedPSBDate} - PSB`;
      const psbDescription = `Penilaian Sebelum Berjalan for ${formattedPSBDate}`;
      
      // Create PSB folder (ID will be auto-generated by database)
      const [psbFolder] = await tx.insert(contractFolder).values({
        contractId,
        name: psbFolderName,
        description: psbDescription,
        path: sql`''::ltree`, // Temporary empty path, will update after getting the ID
        fileType: "folder",
        assessmentDate: psbDate,
        createdAt: new Date(),
        updatedAt: new Date(),
      }).returning();

      // Now update the path with the correct value using the generated ID
      await tx.update(contractFolder).set({
        path: sql`${psbFolder.id}::ltree`,
        updatedAt: new Date(),
      }).where(eq(contractFolder.id, psbFolder.id));
      
      createdFolderIds.push(psbFolder.id);
    }
  }

  return { assessmentDates, finalAssessmentDate, createdFolderIds };
}

/**
 * Create a single assessment folder for a contract
 * @param contractId 
 * @param assessmentDate 
 * @param folderType 'PB' | 'PA' | 'PSB'
 * @param tx 
 */
export async function createSingleAssessmentFolder(
  contractId: string,
  assessmentDate: Date,
  folderType: 'PB' | 'PA' | 'PSB',
  tx: DbOrTx = db
) {
  // Get contract details
  const contractData = await getContractById(contractId);

  if (!contractData) {
    throw new Error(`Contract with ID ${contractId} not found`);
  }

  // Validate date is within contract period
  const startDate = new Date(contractData.startDate);
  const endDate = new Date(contractData.endDate);
  
  if (assessmentDate < startDate || assessmentDate > endDate) {
    throw new Error("Assessment date must be between contract start and end dates");
  }

  // Format date as DD-MM-YYYY for folder name
  const formattedDate = `${String(assessmentDate.getDate()).padStart(2, '0')}-${String(assessmentDate.getMonth() + 1).padStart(2, '0')}-${assessmentDate.getFullYear()}`;
  
  // Determine folder name and description
  const folderName = `${formattedDate} - ${folderType}`;
  const description = folderType === 'PA' 
    ? `Penilaian Akhir for ${formattedDate}` 
    : folderType === 'PSB'
    ? `Penilaian Sebelum Berjalan for ${formattedDate}`
    : `Penilaian Berjalan for ${formattedDate}`;
  
  // Initialize all assessment folders as incomplete
  // They will be marked complete when they meet their completion criteria
  const isComplete = false;
  
  // Create the assessment folder (ID will be auto-generated by database)
  const [newFolder] = await tx.insert(contractFolder).values({
    contractId,
    name: folderName,
    description: description,
    path: sql`''::ltree`, // Temporary empty path, will update after getting the ID
    fileType: "folder",
    isComplete: isComplete, // Initialize as incomplete for all assessment folders
    assessmentDate: assessmentDate,
    createdAt: new Date(),
    updatedAt: new Date(),
  }).returning();

  // Now update the path with the correct value using the generated ID
  await tx.update(contractFolder).set({
    path: sql`${newFolder.id}::ltree`,
    updatedAt: new Date(),
  }).where(eq(contractFolder.id, newFolder.id));

  return newFolder;
}

/**
 * Create a subfolder under a parent folder
 * @param parentFolderId 
 * @param folderName 
 * @param description 
 * @param tx 
 * @returns The created folder
 */
export async function createSubfolder(
  parentFolderId: string,
  folderName: string,
  description: string = '',
  tx: DbOrTx = db
) {
  // Verify parent folder exists
  const parentFolder = await tx.query.contractFolder.findFirst({
    where: eq(contractFolder.id, parentFolderId)
  });

  if (!parentFolder) {
    throw new Error(`Parent folder with ID ${parentFolderId} not found`);
  }

  // Prevent creating subfolders under A. RENCANA K3LL or Elements 3-8
  if (parentFolder.name === 'A. RENCANA K3LL' || /^[3-8]\s/.test(parentFolder.name)) {
    throw new Error("Tidak dapat menambahkan subfolder pada folder induk elemen ini. Subfolder hanya dapat ditambahkan pada sub-elemen atau elemen 1 dan 2.");
  }

  // Check if root assessment folder is finalized
  let rootAncestor = parentFolder;
  while (rootAncestor.parentId) {
    const parent = await tx.query.contractFolder.findFirst({
      where: eq(contractFolder.id, rootAncestor.parentId)
    });
    if (!parent) break;
    rootAncestor = parent;
  }
  if (rootAncestor.isFinal) {
    throw new Error("Folder penilaian sudah difinalisasi. Penambahan subfolder tidak diizinkan.");
  }

  // Create the new subfolder (ID will be auto-generated by database)
  const [newFolder] = await tx.insert(contractFolder).values({
    contractId: parentFolder.contractId,
    parentId: parentFolderId,
    name: folderName,
    description: description,
    path: sql`''::ltree`, // Temporary empty path, will update after getting the ID
    fileType: "folder",
    isComplete: false, // Initialize as not complete
    createdAt: new Date(),
    updatedAt: new Date(),
  }).returning();

  // Now update the path with the correct value using the generated ID
  const folderPath = parentFolder.path ? `${parentFolder.path}.${newFolder.id}` : newFolder.id;
  
  await tx.update(contractFolder).set({
    path: sql`${folderPath}::ltree`,
    updatedAt: new Date(),
  }).where(eq(contractFolder.id, newFolder.id));

  // Return the updated folder
  const updatedFolder = await tx.query.contractFolder.findFirst({
    where: eq(contractFolder.id, newFolder.id)
  });

  return updatedFolder;
}

/**
 * Check if an assessment folder is complete (has files in its K3LL structure)
 * @param folderId 
 * @returns Boolean indicating if the folder is complete
 */
export async function isAssessmentFolderComplete(folderId: string): Promise<boolean> {
  return await isFolderStructureComplete(folderId);
}

/**
 * Update contractor note for a folder (only for contractor role)
 * @param folderId 
 * @param noteContractor 
 * @param tx 
 */
export async function updateFolderNoteContractor(
  folderId: string,
  noteContractor: string,
  tx: DbOrTx = db,
  updatedBy?: string,
) {
  // Verify folder exists
  const folder = await tx.query.contractFolder.findFirst({
    where: eq(contractFolder.id, folderId)
  });

  if (!folder) {
    throw new Error(`Folder with ID ${folderId} not found`);
  }

  // Update the note_contractor field
  const changed = noteContractor !== (folder.noteContractor ?? '');
  await tx.update(contractFolder).set({
    noteContractor: noteContractor,
    // who wrote the contractor note (shown in the Catatan panel)
    ...(changed ? { noteContractorUpdatedBy: updatedBy ?? null, noteContractorUpdatedAt: new Date() } : {}),
    updatedAt: new Date(),
  }).where(eq(contractFolder.id, folderId));

  return {
    folderId: folder.id,
    folderName: folder.name,
    noteContractor: noteContractor
  };
}

/**
 * Update completion status for all assessment folders in a contract
 * @param contractId 
 * @param tx 
 */
export async function updateAllAssessmentFoldersCompletionStatus(
  contractId: string,
  tx: DbOrTx = db
) {
  // Get all assessment folders for this contract
  const assessmentFolders = await tx.query.contractFolder.findMany({
    where: (fields, { eq, and, or }) => 
      and(
        eq(fields.contractId, contractId),
        or(
          sql`name LIKE '% - PB'`,
          sql`name LIKE '% - PA'`,
          sql`name LIKE '% - PSB'`
        )
      ),
  });

  // Update completion status for each folder
  for (const folder of assessmentFolders) {
    const isComplete = await isFolderStructureComplete(folder.id);
    await tx.update(contractFolder).set({
      isComplete,
      updatedAt: new Date()
    }).where(eq(contractFolder.id, folder.id));
  }
}

/**
 * Delete a folder and all its associated files and subfolders recursively
 * @param folderId 
 * @param tx 
 * @returns Object with success status and deletion information
 */
export async function deleteFolder(
  folderId: string,
  tx: DbOrTx = db
) {
  try {
    // First, get the folder to be deleted
    const folder = await tx.query.contractFolder.findFirst({
      where: eq(contractFolder.id, folderId)
    });

    if (!folder) {
      throw new Error(`Folder with ID ${folderId} not found`);
    }

    // Protect K3LL structure folders (A. RENCANA K3LL, Elements 1-8, Sub-elements 1.1-8.2) from deletion
    if (isK3LLStructureFolder(folder.name)) {
      throw new Error(`Folder struktur standar K3LL tidak dapat dihapus: ${folder.name}`);
    }

    // Check if under a finalized assessment folder
    let currentAncestor = folder;
    while (currentAncestor.parentId) {
      const parent = await tx.query.contractFolder.findFirst({
        where: eq(contractFolder.id, currentAncestor.parentId)
      });
      if (!parent) break;
      currentAncestor = parent;
    }
    if (currentAncestor.isFinal) {
      throw new Error("Folder penilaian sudah difinalisasi. Folder di dalamnya tidak dapat dihapus.");
    }

    // Check if this is an assessment folder (PB or PA or PSB)
    const isFolderAssessmentType = folder.name.endsWith(' - PB') || folder.name.endsWith(' - PA') || folder.name.endsWith(' - PSB');
    
    // If it's an assessment folder, we need to update the contract dates
    // Note: PSB folder doesn't need special handling for contract dates
    const isPBFolder = folder.name.endsWith(' - PB');
    const isPAFolder = folder.name.endsWith(' - PA');
    
    if (isFolderAssessmentType && (isPBFolder || isPAFolder)) {
      // Get the contract
      const contractData = await tx.query.contract.findFirst({
        where: eq(contract.id, folder.contractId)
      });
      
      if (contractData) {
        if (isPAFolder) {
          // If deleting PA folder, we need to update the final assessment date
          // Set it to the contract end date as default
          await tx.update(contract).set({
            finalAssessmentDate: contractData.endDate,
            updatedAt: new Date(),
          }).where(eq(contract.id, folder.contractId));
        } else if (isPBFolder && Array.isArray(contractData.nearestOngoingAssessmentDate)) {
          // If deleting PB folder, we need to remove the date from nearestOngoingAssessmentDate
          // Extract date from folder name (first 10 characters: DD-MM-YYYY)
          const folderDateStr = folder.name.substring(0, 10);
          // Convert DD-MM-YYYY to YYYY-MM-DD for comparison
          const [day, month, year] = folderDateStr.split('-');
          const folderDateISO = `${year}-${month}-${day}`;
          
          // Filter out the date that matches this folder
          const updatedDates = contractData.nearestOngoingAssessmentDate.filter((date: any) => {
            // Handle both Date objects and string dates
            if (typeof date === 'string') {
              // If it's already in YYYY-MM-DD format
              if (date.length === 10 && date[4] === '-' && date[7] === '-') {
                return date !== folderDateISO;
              }
              // If it's an ISO string, extract the date part
              return date.split('T')[0] !== folderDateISO;
            } else if (date && typeof date === 'object' && date.toISOString) {
              // Handle Date objects
              return date.toISOString().split('T')[0] !== folderDateISO;
            }
            return true;
          });
          
          await tx.update(contract).set({
            nearestOngoingAssessmentDate: updatedDates as any,
            updatedAt: new Date(),
          }).where(eq(contract.id, folder.contractId));
        }
      }
    }

    // Delete all descendants (files and subfolders) of this folder using ltree path
    // This ensures we delete all children, grandchildren, etc. in one operation
    console.log(`Deleting descendants of folder ${folderId} with path ${folder.path}`);
    
    // First, get all descendants to delete their physical files
    const descendants = await tx.query.contractFolder.findMany({
      where: sql`${contractFolder.path} <@ ${folder.path} AND ${contractFolder.id} != ${folderId}`
    });
    
    // Delete physical files for all descendants that are files (not folders)
    for (const descendant of descendants) {
      if (descendant.fileType === 'file' && descendant.filePath) {
        try {
          // Construct the full path to the file
          const fileUploadPath = uploadsPath('csms', 'contracts', descendant.contractId, descendant.id);
          // Delete the file and its thumbnail folder
          await fs.rm(fileUploadPath, { recursive: true, force: true });
          console.log(`Deleted physical file: ${fileUploadPath}`);
        } catch (error: unknown) {
          // Log the error but continue with database deletion
          if (error instanceof Error) {
            console.warn(`Failed to delete physical file for ${descendant.id}:`, error.message);
          } else {
            console.warn(`Failed to delete physical file for ${descendant.id}: Unknown error occurred`);
          }
        }
      }
    }
    
    // Delete the physical folder for the folder being deleted (if it's a depth 0 folder)
    // Physical folders are stored at: uploads/csms/contracts/{contractId}/{depth0FolderId}/
    if (folder.depth === 0) {
      try {
        const folderUploadPath = uploadsPath('csms', 'contracts', folder.contractId, folder.id);
        await fs.rm(folderUploadPath, { recursive: true, force: true });
        console.log(`Deleted physical folder: ${folderUploadPath}`);
      } catch (error: unknown) {
        if (error instanceof Error) {
          console.warn(`Failed to delete physical folder for ${folder.id}:`, error.message);
        } else {
          console.warn(`Failed to delete physical folder for ${folder.id}: Unknown error occurred`);
        }
      }
    }
    
    const deletedDescendants = await tx.delete(contractFolder).where(
      sql`${contractFolder.path} <@ ${folder.path} AND ${contractFolder.id} != ${folderId}`
    );
    console.log(`Deleted ${deletedDescendants.rowCount} descendants`);

    // Delete the folder itself from the database
    console.log(`Deleting folder ${folderId}`);
    const deletedFolderResult = await tx.delete(contractFolder).where(eq(contractFolder.id, folderId));
    console.log(`Deleted folder result: ${deletedFolderResult.rowCount} rows`);

    // If this was a child of a depth 0 assessment folder, mark the parent as incomplete and status as pending
    if (folder.parentId) {
      const parentFolder = await tx.query.contractFolder.findFirst({
        where: eq(contractFolder.id, folder.parentId)
      });
      
      // Check if parent is a depth 0 assessment folder
      if (parentFolder && parentFolder.depth === 0) {
        const isParentAssessmentFolder = parentFolder.name.endsWith(' - PB') || parentFolder.name.endsWith(' - PA') || parentFolder.name.endsWith(' - PSB');
        if (isParentAssessmentFolder) {
          await tx.update(contractFolder).set({
            isComplete: false,
            status: 'pending',
            updatedAt: new Date(),
          }).where(eq(contractFolder.id, folder.parentId));
        }
      }
    }

    // Update parent folder completion status and recalculate scores
    if (folder.parentId) {
      // First update parent completion status
      await updateAllAssessmentFoldersCompletionStatus(folder.contractId, tx);
      
      // Get ancestors to recalculate their scores
      const ancestors = await getAncestors(folder.parentId, tx);
      
      // Build the complete ancestor list including the direct parent
      const allFoldersToUpdate = [folder.parentId, ...ancestors];
      
      // Recalculate and update scores from child to parent (bottom-up)
      for (const folderId of allFoldersToUpdate) {
        const calculatedScore = await calculateFolderScore(folderId, tx);
        await tx.update(contractFolder).set({
          score: calculatedScore.toString(),
          updatedAt: new Date(),
        }).where(eq(contractFolder.id, folderId));
      }
    }
    
    // If this was an assessment folder, update completion status for all assessment folders in the contract
    if (isFolderAssessmentType) {
      await updateAllAssessmentFoldersCompletionStatus(folder.contractId, tx);
    }

    return {
      folderId: folder.id,
      folderName: folder.name
    };
  } catch (error) {
    console.error(`Error in deleteFolder for folder ${folderId}:`, error);
    throw error;
  }
}

/**
 * Check if a folder is part of the K3LL structure
 * @param folderName 
 * @returns Boolean indicating if the folder is part of K3LL structure
 */
export function isK3LLStructureFolder(folderName: string): boolean {
  // Check if folder is part of K3LL structure based on exact naming patterns from K3LL_STRUCTURE
  const isK3LLFolder = folderName === 'A. RENCANA K3LL' || 
                      /^([1-8])\s/.test(folderName) ||  // Numbered K3LL folders (1, 2, 3, etc.)
                      /^([1-8])\.(\d+)/.test(folderName); // Sub-numbered K3LL folders (1.1, 1.2, etc.)
  
  return isK3LLFolder;
}

/**
 * Check if a folder or any of its parents is part of the K3LL structure
 * @param folderId 
 * @returns Boolean indicating if the folder is part of K3LL structure
 */
export async function isFolderInK3LLStructure(folderId: string): Promise<boolean> {
  // Get the folder
  const folder = await db.query.contractFolder.findFirst({
    where: eq(contractFolder.id, folderId)
  });

  if (!folder) {
    return false;
  }

  // Check if this folder itself is part of K3LL structure
  if (isK3LLStructureFolder(folder.name)) {
    return true;
  }

  // Check if any parent is part of K3LL structure
  if (folder.parentId) {
    return await isFolderInK3LLStructure(folder.parentId);
  }

  return false;
}
